// The site only uses a few dozen Chinese characters, but @fontsource/noto-serif-sc
// ships ~120 @font-face blocks. This keeps only the blocks whose unicode-range
// covers a character that actually appears in src/, and writes them to
// src/styles/fonts-zh.css. Runs automatically before `dev` and `build`.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const SRC = path.resolve('src');
const FONT_CSS = path.resolve('node_modules/@fontsource/noto-serif-sc/600.css');
const OUT = path.resolve('src/styles/fonts-zh.css');

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(jsx?|css)$/.test(e.name) && p !== OUT) out.push(p);
  }
  return out;
}

const chars = new Set();
for (const file of await walk(SRC)) {
  for (const ch of await readFile(file, 'utf8')) {
    const cp = ch.codePointAt(0);
    if ((cp >= 0x3000 && cp <= 0x9fff) || (cp >= 0xf900 && cp <= 0xfaff)) chars.add(cp);
  }
}

const parseRange = (r) =>
  r.split(',').map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
    if (a.includes('?')) return [parseInt(a.replace(/\?/g, '0'), 16), parseInt(a.replace(/\?/g, 'f'), 16)];
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });

const css = await readFile(FONT_CSS, 'utf8');
const blocks = css.match(/@font-face\s*{[^}]*}/g) || [];
const fontDir = '../../node_modules/@fontsource/noto-serif-sc/files/';
const kept = blocks.filter((block) => {
  const m = block.match(/unicode-range:\s*([^;]+);/);
  if (!m) return false;
  const ranges = parseRange(m[1]);
  return [...chars].some((cp) => ranges.some(([a, b]) => cp >= a && cp <= b));
});

const output =
  `/* Generated by scripts/build-zh-font.mjs — do not edit. ${chars.size} glyphs, ${kept.length} subsets. */\n` +
  kept.map((b) => b.replace(/url\(\.\/files\//g, `url(${fontDir}`)).join('\n') +
  '\n';
await writeFile(OUT, output);
console.log(`fonts-zh.css: ${chars.size} chinese glyphs → ${kept.length}/${blocks.length} font subsets`);
